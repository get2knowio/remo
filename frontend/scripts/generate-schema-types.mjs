#!/usr/bin/env node
// Generates `src/api/generated/schema.d.ts` from the checked-in
// `src/api/generated/openapi.json` REST contract (feature 020).
//
// Uses openapi-typescript's JS API directly (mirroring generate-frame-types.mjs's
// existing pattern for the frame contract) rather than shelling out to the CLI
// binary, so both the npm `generate:types` script and `check-types-fresh.mjs`'s
// freshness check share ONE implementation instead of two independently
// hand-maintained invocations that could silently drift apart (e.g. a future
// CLI flag added to only one of the two copies).
//
// The openapi-typescript CLI prepends a fixed header comment that its JS API
// does not add on its own; SCHEMA_HEADER reproduces it verbatim so switching
// from the CLI to the JS API here doesn't change a single byte of the
// checked-in schema.d.ts.
//
// Usable two ways:
//   - CLI:      node scripts/generate-schema-types.mjs
//   - Imported: import { generateSchemaTypes } from "./generate-schema-types.mjs"
//               (used by check-types-fresh.mjs to regenerate into a temp path)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const __dirname = dirname(fileURLToPath(import.meta.url));
const frontendRoot = join(__dirname, "..");

export const OPENAPI_JSON = join(frontendRoot, "src", "api", "generated", "openapi.json");
export const SCHEMA_DTS_OUT = join(frontendRoot, "src", "api", "generated", "schema.d.ts");

// Reproduces the openapi-typescript CLI's own fixed header byte-for-byte, so
// generating via the JS API here never diverges from what the CLI used to
// produce.
const SCHEMA_HEADER = `/**
 * This file was auto-generated by openapi-typescript.
 * Do not make direct changes to the file.
 */

`;

/** Reads openapi.json, generates TypeScript, and writes it to `outPath`
 * (defaults to the checked-in path). Returns the generated text. */
export async function generateSchemaTypes(outPath = SCHEMA_DTS_OUT) {
  const doc = JSON.parse(readFileSync(OPENAPI_JSON, "utf8"));
  const ast = await openapiTS(doc);
  const body = astToString(ast);
  const text = SCHEMA_HEADER + body;

  writeFileSync(outPath, text);
  return text;
}

const isCliEntryPoint = import.meta.url === `file://${process.argv[1]}`;
if (isCliEntryPoint) {
  generateSchemaTypes()
    .then(() => {
      console.log(`wrote ${SCHEMA_DTS_OUT}`);
    })
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}
