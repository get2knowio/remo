class TestStaleness:
    def test_reads_the_stamped_version(self, home):
        install("bash", SCRIPT, edit_rc=False, home=home)
        assert installed_version("bash", home=home) == "9.9.9"

    def test_unstamped_script_reads_as_unknown(self, home):
        """Scripts generated by remo <= 2.2.0 carry no stamp. Unknown is
        treated as stale, which is the safe direction: the nudge is cheap and
        those are exactly the files that break."""
        install("bash", "_remo() { :; }\n", edit_rc=False, home=home)
        assert installed_version("bash", home=home) is None
        assert is_stale("bash", "9.9.9", home=home) is True

    def test_matching_version_is_not_stale(self, home):
        install("bash", SCRIPT, edit_rc=False, home=home)
        assert is_stale("bash", "9.9.9", home=home) is False

    def test_older_version_is_stale(self, home):
        install("bash", SCRIPT, edit_rc=False, home=home)
        assert is_stale("bash", "10.0.0", home=home) is True

    def test_absent_script_is_not_stale(self, home):
        """Someone who never installed completion should never be nudged about
        it — absent is not stale, it is uninterested."""
        assert is_stale("bash", "9.9.9", home=home) is False
        assert installed_version("bash", home=home) is None
