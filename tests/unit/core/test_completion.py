"""Tests for core.completion — layout, detection, install, staleness.

The install path is the one place remo writes to files it does not own
(``~/.bashrc``, ``~/.zshrc``), so the coverage here leans on idempotency and
on never touching an rc file without consent.
"""

from __future__ import annotations

import os

import pytest

from remo_cli.core import completion
from remo_cli.core.completion import (
    SHELLS,
    detect_shell,
    install,
    installed_version,
    is_stale,
    layout_for,
)

SCRIPT = "# remo shell completion for bash — generated by remo 9.9.9.\n_remo() { :; }\n"


@pytest.fixture
def home(tmp_path, monkeypatch):
    """An isolated HOME with REMO_HOME pointed inside it.

    XDG_CONFIG_HOME is cleared so fish paths are deterministic — a developer
    who happens to export it should not get different results than CI.
    """
    monkeypatch.setenv("REMO_HOME", str(tmp_path / ".config" / "remo"))
    monkeypatch.delenv("XDG_CONFIG_HOME", raising=False)
    return tmp_path


