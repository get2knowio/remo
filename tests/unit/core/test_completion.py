# layout
# ---------------------------------------------------------------------------


class TestLayout:
    def test_fish_honours_xdg_config_home(self, home, monkeypatch, tmp_path):
        """fish resolves its config dir from $XDG_CONFIG_HOME when set. Writing
        to ~/.config/fish anyway puts the script where fish never looks, and
        fish reports that by silently completing filenames — the bug this
        regression-tests, caught by the fish integration job in CI.
        """
        xdg = tmp_path / "xdg"
        monkeypatch.setenv("XDG_CONFIG_HOME", str(xdg))
        layout = layout_for("fish", home=home)
        assert layout.script_path == xdg / "fish" / "completions" / "remo.fish"

    def test_fish_falls_back_to_dot_config_without_xdg(self, home, monkeypatch):
        monkeypatch.delenv("XDG_CONFIG_HOME", raising=False)
        layout = layout_for("fish", home=home)
        assert layout.script_path == home / ".config/fish/completions/remo.fish"

    def test_fish_needs_no_rc_edit(self, home, monkeypatch):
        monkeypatch.delenv("XDG_CONFIG_HOME", raising=False)
        layout = layout_for("fish", home=home)
        assert layout.script_path == home / ".config/fish/completions/remo.fish"
        # fish scans its completions dir natively — editing config.fish would be
        # gratuitous, and the absence of an rc path is what the CLI branches on.
        assert layout.rc_path is None
        assert layout.source_line is None

    @pytest.mark.parametrize(
        ("shell", "rc_name"), [("bash", ".bashrc"), ("zsh", ".zshrc")]
    )
    def test_bash_and_zsh_get_a_dropin_plus_rc_line(self, home, shell, rc_name):
        layout = layout_for(shell, home=home)
        assert layout.script_path.name == f"completion.{shell}"
        assert layout.rc_path == home / rc_name
        assert layout.source_line is not None
        # Absolute path, not ~ or $HOME: REMO_HOME may point elsewhere entirely
        # and a wrong source line fails silently at shell startup.
        assert str(layout.script_path) in layout.source_line

    def test_unknown_shell_rejected(self, home):
        with pytest.raises(ValueError, match="Unsupported shell"):
            layout_for("nushell", home=home)


