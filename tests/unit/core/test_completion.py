class TestInstall:
    def test_writes_script_and_reports_it(self, home):
        outcome = install("bash", SCRIPT, edit_rc=True, home=home)
        assert outcome.script_written is True
        assert outcome.script_path.read_text() == SCRIPT

    def test_rerun_with_identical_script_is_a_noop(self, home):
        install("bash", SCRIPT, edit_rc=True, home=home)
        outcome = install("bash", SCRIPT, edit_rc=True, home=home)
        assert outcome.script_written is False
        assert outcome.rc_line_added is False

    def test_rc_line_added_once_across_repeated_installs(self, home):
        for _ in range(3):
            install("bash", SCRIPT, edit_rc=True, home=home)
        rc = (home / ".bashrc").read_text()
        # The `>> ~/.bashrc` form this replaces duplicated the whole script on
        # every run; the whole point of the indirection is that this stays 1.
        # Counted by marker, not by path: the loader line names the path twice
        # (`[ -f "..." ] && source "..."`).
        assert rc.count("# remo shell completion") == 1
        assert len([ln for ln in rc.splitlines() if "completion.bash" in ln]) == 1

    def test_without_consent_the_rc_is_never_touched(self, home):
        rc = home / ".bashrc"
        rc.write_text("# untouched\n")
        outcome = install("bash", SCRIPT, edit_rc=False, home=home)
        assert rc.read_text() == "# untouched\n"
        assert outcome.rc_line_added is False
        # The caller gets the line to print so the user can add it by hand.
        assert outcome.pending_source_line is not None
        assert str(outcome.script_path) in outcome.pending_source_line

    def test_existing_rc_reference_suppresses_both_edit_and_prompt(self, home):
        """A hand-written or older-format loader line still counts as wired up
        — matching on the path, not the exact wording, avoids a duplicate."""
        layout = layout_for("bash", home=home)
        (home / ".bashrc").write_text(f". {layout.script_path}  # hand-rolled\n")
        outcome = install("bash", SCRIPT, edit_rc=True, home=home)
        assert outcome.rc_line_added is False
        assert outcome.pending_source_line is None

    def test_appends_to_rc_lacking_trailing_newline(self, home):
        """Appending to a file whose last line is unterminated must not weld
        the loader onto the end of the user's last command."""
        (home / ".bashrc").write_text("export FOO=1")
        install("bash", SCRIPT, edit_rc=True, home=home)
        lines = (home / ".bashrc").read_text().splitlines()
        assert lines[0] == "export FOO=1"

    def test_missing_rc_is_created(self, home):
        assert not (home / ".bashrc").exists()
        install("bash", SCRIPT, edit_rc=True, home=home)
        assert "completion.bash" in (home / ".bashrc").read_text()

    def test_fish_install_touches_no_rc(self, home):
        outcome = install("fish", SCRIPT, edit_rc=True, home=home)
        assert outcome.script_path.exists()
        assert outcome.rc_path is None
        assert outcome.rc_line_added is False
        assert outcome.pending_source_line is None


